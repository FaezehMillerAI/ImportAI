"""
EduLead Agent: آموزش و مشاوره استراتژیک واردات، تحلیل سودآوری و ترغیب هوشمندانه
"""
from services.llm_service import LLMService

SYSTEM_PROMPT = """
شما یک مشاور ارشد و بسیار باهوش تجارت بین‌الملل و سورسینگ کالا (EduLead Strategic Advisor) هستید.

دستورالعمل‌های حیاتی لحن و رفتار:
۱. به هیچ وجه در ابتدای هر پیام جملات تکراری و کلیشه‌ای رباتیک مانند «سلام من آریا هستم» یا «من ایجنت فلان هستم» را تکرار نکنید! مانند یک مشاور واقعی، مستقیم، گرم و مسلط به سوال کاربر پاسخ دهید.
۲. پاسخ‌های شما باید عمیق، کاربردی، واقع‌گرایانه و بدون شعار باشند (مثلاً تحلیل حاشیه سود واقعی، تفاوت قیمت کارخانه چین و بازار ایران، نحوه دور زدن واسطه‌ها، اهمیت بازرسی PSI و اعتبارسنجی QCC).
۳. اگر کاربر سوالی پرسید، ابتدا جواب دقیق و تخصصی او را بدهید و در انتهای صحبت به شکل کاملاً طبیعی او را به تست شبیه‌ساز ۵۰ هزار دلاری یا بررسی دقیق‌تر کالا دعوت کنید.
۴. زبان پاسخگویی باید متناسب با زبان کاربر (فارسی روان و حرفه‌ای یا انگلیسی دقیق بیزینسی) باشد.
"""

class EduLeadAgent:
    @staticmethod
    async def process_chat(user_message: str) -> str:
        return await LLMService.generate_response(SYSTEM_PROMPT, user_message)

    @staticmethod
    def get_gamification_scenario(capital: float = 50000, industry: str = "machinery"):
        return {
            "title": f"شبیه‌سازی واردات با سرمایه {capital:,.0f} دلار در صنعت {industry}",
            "steps": [
                {"step": 1, "question": "انتخاب صنعت و کالای اصلی"},
                {"step": 2, "question": "انتخاب کارخانه: قیمت ارزان vs کارخانه ثبت‌شده در QCC"},
                {"step": 3, "question": "بازرسی قبل از حمل (PSI): آیا کنترل کیفیت انجام شود؟"},
                {"step": 4, "question": "تخصیص ارز: ارز نیما vs ارز صادراتی"}
            ]
        }
